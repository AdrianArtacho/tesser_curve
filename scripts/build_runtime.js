// Bundle the pure engine with its Max adapter: legacy js include() is search-path dependent.
const fs = require('node:fs');
const path = require('node:path');
const dir = path.join(__dirname, '../tesser_curve/code');
const banner = '// GENERATED by scripts/build_runtime.js. Edit tesser_ramp_core.js and tesser_curve_engine.js.\n';
const core = fs.readFileSync(path.join(dir, 'tesser_ramp_core.js'), 'utf8');
const adapter = fs.readFileSync(path.join(dir, 'tesser_curve_engine.js'), 'utf8').replace('include("tesser_ramp_core.js");', '');
const content = banner + core + '\n' + adapter;
const patchers = path.join(dir, '../patchers');
const files = {
    'tesser_curve_runtime.js': content,
    'tesser_session_runtime.js': '// GENERATED by scripts/build_runtime.js. Edit code/tesser_session_watch.js.\n' +
        fs.readFileSync(path.join(dir, 'tesser_session_watch.js'), 'utf8')
};
if (process.argv.includes('--check')) {
    for (const [name, text] of Object.entries(files)) {
        if (fs.readFileSync(path.join(patchers, name), 'utf8') !== text) {
            throw new Error('Runtime bundle is stale. Run node scripts/build_runtime.js');
        }
    }
} else { for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(patchers, name), text); }
